def cmd_affected(args) -> int:
    root = find_root(args.root)
    wiki = require_wiki(root)
    if not is_git(root):
        fail("not a git repository, so changes cannot be detected", 3)
    changed = set(status_entries(root))
    base = args.since or git_out(root, "rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}")
    if base:
        listed = git_out(root, "diff", "--name-only", f"{base}...HEAD")
        if listed is None:
            fail(f"cannot compare against {base}")
        changed |= set(filter(None, listed.split("\n")))
    prefix = f"{WIKI}/"
    code = sorted(c for c in changed if not c.startswith(prefix))
    docs = {c[len(prefix):] for c in changed if c.startswith(prefix)}
    pages = load_pages(wiki)
    mapped = set()
    print(f"Changed code files: {len(code)}" + (f" (compared with {base})" if base else ""))
    for page in pages:
        files = [c for c in code if matches(c, page.sources)]
        if files:
            mapped.update(files)
            if page.status == "superseded":
                continue
            state = "wiki page changed" if page.rel in docs else "NEEDS REVIEW"
            if page.status in PLANNED_STATUSES:
                state += f" (status {page.status}: if this builds it, set implemented)"
            print(f"  {WIKI}/{page.rel}: {state}, {len(files)} file(s): {', '.join(files[:5])}")
    unmapped = [c for c in code if c not in mapped]
    if unmapped:
        print(f"Not covered by any page ({len(unmapped)}), so add to sources or start a new feature if it matters:")
        for path in unmapped[:30]:
            print(f"  {path}")
        if len(unmapped) > 30:
            print(f"  ...and {len(unmapped) - 30} more")
    return 0


