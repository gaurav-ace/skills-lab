    for kind in kinds:
        if kind not in PAGE_TYPES or kind in ("design", "learning"):
            fail(f"cannot scaffold '{kind}' here. Use the design command for design pages; "
                 "learning.md is automatic. Other types: " + ", ".join(PAGE_TYPES))
