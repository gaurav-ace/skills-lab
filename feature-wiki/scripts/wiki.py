def fail(message: str, code: int = 1) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(code)


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
    )


def git_out(root: Path, *args: str) -> str | None:
    result = git(root, *args)
    return result.stdout.strip() if result.returncode == 0 else None


def find_root(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).resolve()
    cwd = Path.cwd()
    top = git_out(cwd, "rev-parse", "--show-toplevel")
    if top:
        return Path(top)
    for candidate in [cwd, *cwd.parents]:
        if (candidate / WIKI / MARKER).exists():
            return candidate
    return cwd


def is_git(root: Path) -> bool:
    return git_out(root, "rev-parse", "--is-inside-work-tree") == "true"


def require_wiki(root: Path) -> Path:
    wiki = root / WIKI
    if not (wiki / MARKER).exists():
        fail(f"no feature wiki at {wiki}. Create one with: wiki.py init, or backfill via the skill.", 3)
    return wiki


# ---------------------------------------------------------------- page parsing


def parse_inline_list(value: str) -> list[str]:
    items = re.findall(r"""\s*("[^"]*"|'[^']*'|[^,]+)\s*(?:,|$)""", value[1:-1])
    return [i.strip().strip("\"'") for i in items if i.strip()]


def parse_frontmatter(text: str) -> tuple[dict, int]:
    """Parse the small YAML subset pages use. Returns (fields, body start line, 1-based)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, 1
    meta: dict = {}
    current = None
    for index, line in enumerate(lines[1:], start=2):
        if line.strip() == "---":
            return meta, index + 1
        block_item = re.match(r"\s*-\s+(.*)", line)
        if block_item and current:
            if not isinstance(meta[current], list):
                meta[current] = []
            meta[current].append(block_item.group(1).strip().strip("\"'"))
            continue
        pair = re.match(r"([A-Za-z_]+):\s*(.*)", line)
        if pair:
            current, value = pair.group(1), pair.group(2).strip()
            if value.startswith("[") and value.endswith("]"):
                meta[current] = parse_inline_list(value)
            else:
                meta[current] = value.strip("\"'")
    return {}, 1


def as_list(value) -> list[str]:
    if isinstance(value, list):
        return value
    return [value] if value else []


class Page:
    def __init__(self, path: Path, wiki: Path):
        self.path = path
        self.rel = path.relative_to(wiki).as_posix()
        self.text = path.read_text(encoding="utf-8", errors="replace")
        self.meta, self.body_start = parse_frontmatter(self.text)
        self.lines = self.text.split("\n")
        self.line_count = len(self.lines) - (1 if self.lines and self.lines[-1] == "" else 0)
        self.slug = ROOT_SLUG if path.parent == wiki else path.parent.name
        self.name = path.stem
        self.id = f"{self.slug}/{self.name}"
        self.sources = as_list(self.meta.get("sources"))
        self.sections = self._sections()

    def field(self, name: str) -> str:
        value = self.meta.get(name, "")
        return value if isinstance(value, str) else ", ".join(value)

    @property
    def status(self) -> str:
        return self.field("status")

    @property
    def tracks_code(self) -> bool:
        """Planned and superseded pages don't claim to describe the current code."""
        return self.status not in PLANNED_STATUSES and self.status != "superseded"

    @property
    def tag(self) -> str:
        if self.status == "superseded":
            return f"[superseded by {self.field('superseded_by')}]"
        return f"[{self.status}]" if self.status else ""

    def _sections(self) -> list[dict]:
        """Sections from ## and ### headings. Each ends where the next one of equal or higher level starts."""
        heads = []
        fenced = False
        for number in range(self.body_start, self.line_count + 1):
            line = self.lines[number - 1]
            if line.lstrip().startswith(("```", "~~~")):
                fenced = not fenced
            match = None if fenced else re.match(r"(#{2,3})\s+(.*\S)\s*$", line)
            if match:
                heads.append((len(match.group(1)), match.group(2), number))
        sections = []
        for position, (level, heading, start) in enumerate(heads):
            end = self.line_count
            for later_level, _, later_start in heads[position + 1:]:
                if later_level <= level:
                    end = later_start - 1
                    break
            sections.append({"level": level, "heading": heading, "start": start, "end": end})
        return sections

    def chunks(self) -> list[dict]:
        """Non-overlapping search units: each runs from one heading to the next heading of any level."""
        starts = [(s["start"], s["heading"]) for s in self.sections]
        if not starts or starts[0][0] > self.body_start:
            starts.insert(0, (self.body_start, "(intro)"))
        chunks = []
        for position, (start, heading) in enumerate(starts):
            end = starts[position + 1][0] - 1 if position + 1 < len(starts) else self.line_count
            text = "\n".join(self.lines[start - 1:end])
            title_only = all(not l.strip() or l.startswith("#") for l in text.split("\n"))
            if not (heading == "(intro)" and title_only):
                chunks.append({"heading": heading, "start": start, "end": end, "text": text})
        return chunks


def load_pages(wiki: Path, feature: str | None = None) -> list[Page]:
    pages = []
    if (wiki / LEARNING_FILE).exists() and feature in (None, ROOT_SLUG):
        pages.append(Page(wiki / LEARNING_FILE, wiki))
    for path in sorted((wiki / "features").glob("*/*.md")):
        if path.name != "INDEX.md" and (feature is None or path.parent.name == feature):
            pages.append(Page(path, wiki))
    return pages


# ---------------------------------------------------------------- index generation


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def page_sort_key(page: Page) -> tuple:
    order = list(PAGE_TYPES)
    kind = page.field("type")
    return (order.index(kind) if kind in order else len(order), page.status == "superseded", page.name)


def render_root_index(pages: list[Page], has_learning: bool) -> str:
    out = [
        GENERATED, "", "# Feature wiki index", "",
        "Pick the feature by meaning, open its index, then read only the section line range you need.",
        "If that does not settle it, use lexical search: `wiki.py search \"terms\"`.",
        "Pages marked `decided` or `implemented` are binding: raise any conflict before departing from them.",
    ]
    if has_learning:
        out += ["", f"Project-wide lessons: [{LEARNING_FILE}]({LEARNING_FILE})"]
    out += ["", "| Feature | Status | What it is | Keywords | Code |", "|---|---|---|---|---|"]
    for slug in sorted({p.slug for p in pages}):
        group = [p for p in pages if p.slug == slug]
        overview = next((p for p in group if p.name == "overview"), group[0])
        keywords = ", ".join(as_list(overview.meta.get("keywords"))[:12])
        code = ", ".join(f"`{s}`" for s in overview.sources[:3])
        out.append(f"| [{slug}](features/{slug}/INDEX.md) | {overview.status} | {cell(overview.field('summary'))} "
                   f"| {cell(keywords)} | {cell(code)} |")
    return "\n".join(out) + "\n"


def render_feature_index(slug: str, group: list[Page]) -> str:
    overview = next((p for p in group if p.name == "overview"), group[0])
    out = [GENERATED, "", f"# {overview.field('title') or slug}", "", overview.field("summary"), ""]
    for page in sorted(group, key=page_sort_key):
        tag = f" {page.tag}" if page.tag else ""
        out.append(f"## [{page.path.name}]({page.path.name}): {page.field('title')}{tag} ({page.line_count} lines)")
        out.append("")
        out.append(page.field("summary"))
        questions = as_list(page.meta.get("questions"))
        if questions:
            out.append("")
            out.append("Answers: " + " / ".join(questions))
        if page.sections:
            out.append("")
            for section in page.sections:
                indent = "  " if section["level"] == 3 else ""
                out.append(f"{indent}- L{section['start']}-{section['end']} {section['heading']}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def expected_indexes(wiki: Path) -> dict[Path, str]:
    pages = [p for p in load_pages(wiki) if p.slug != ROOT_SLUG]
    result = {wiki / "INDEX.md": render_root_index(pages, (wiki / LEARNING_FILE).exists())}
    for slug in sorted({p.slug for p in pages}):
        group = [p for p in pages if p.slug == slug]
        result[wiki / "features" / slug / "INDEX.md"] = render_feature_index(slug, group)
    return result


def write_learning(path: Path, slug: str, title: str) -> None:
    path.write_text(
        f"---\ntitle: {title} learnings\nfeature: {slug}\ntype: learning\n"
        f"summary: Lessons from building {title}, covering gotchas, corrections and questions worth remembering.\n"
        f"---\n\n# {title} learnings\n\nNo entries yet.\n",
        encoding="utf-8", newline="\n",
    )


def ensure_learning(wiki: Path) -> list[str]:
    """Every wiki folder that holds pages keeps its own learning.md: the root, and one per feature."""
    created = []
    if not (wiki / LEARNING_FILE).exists():
        write_learning(wiki / LEARNING_FILE, ROOT_SLUG, "Project")
        created.append(LEARNING_FILE)
    for folder in sorted(p for p in (wiki / "features").glob("*") if p.is_dir()):
        target = folder / LEARNING_FILE
        overview = folder / "overview.md"
        if overview.exists() and not target.exists():
            meta, _ = parse_frontmatter(overview.read_text(encoding="utf-8", errors="replace"))
            write_learning(target, folder.name, meta.get("title") or folder.name)
            created.append(target.relative_to(wiki).as_posix())
    return created


def build(wiki: Path) -> list[str]:
    changed = ensure_learning(wiki)
    expected = expected_indexes(wiki)
    for path, content in expected.items():
        if not path.exists() or path.read_text(encoding="utf-8", errors="replace") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            changed.append(path.relative_to(wiki).as_posix())
    features = wiki / "features"
    if features.is_dir():
        for orphan in features.glob("*/INDEX.md"):
            if orphan not in expected:
                orphan.unlink()
                changed.append(orphan.relative_to(wiki).as_posix())
    return changed


# ---------------------------------------------------------------- source mapping


def clean_glob(pattern: str) -> str:
    pattern = pattern.strip().removeprefix("./")
    return pattern + "**" if pattern.endswith("/") else pattern


def glob_regex(pattern: str) -> re.Pattern:
    pattern = clean_glob(pattern)
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(f"^{out}(?:/.*)?$")


def matches(path: str, patterns: list[str]) -> bool:
    return any(glob_regex(p).match(path) for p in patterns)


def all_files(root: Path) -> list[str]:
    if is_git(root):
        listed = git_out(root, "ls-files", "-co", "--exclude-standard")
        return listed.split("\n") if listed else []
    files = []
    for folder, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in {"build", "node_modules", WIKI}]
        files += [(Path(folder) / n).relative_to(root).as_posix() for n in names]
    return files


def to_pathspec(pattern: str) -> str:
    return f":(glob){clean_glob(pattern)}"


def status_entries(root: Path, *paths: str) -> list[str]:
    """Every changed or untracked path in the working tree, repo-relative."""
    out = git(root, "status", "--porcelain=v1", "-z", "--untracked-files=all", "--", *paths).stdout
    tokens = out.split("\0")
    entries, i = [], 0
    while i < len(tokens):
        token = tokens[i]
        i += 1
        if len(token) < 4:
            continue
        entries.append(token[3:])
        if token[0] in "RC":
            if i < len(tokens) and tokens[i]:
                entries.append(tokens[i])
            i += 1
    return entries


def stale_commits(root: Path, page: Page) -> list[str]:
    """Commits that changed this page's sources after the page itself last changed.

    A page committed together with its code, or in any later commit, counts as fresh.
    A page with uncommitted edits is being updated right now, so it is not flagged.
    """
    if not page.sources:
        return []
    rel = page.path.relative_to(root).as_posix()
    if status_entries(root, rel):
        return []
    last = git_out(root, "log", "-1", "--format=%H", "--", rel)
    if not last:
        return []
    specs = [to_pathspec(s) for s in page.sources]
    listed = git_out(root, "log", "--format=%h %s", f"{last}..HEAD", "--", *specs)
    return listed.split("\n") if listed else []


# ---------------------------------------------------------------- search


def tokenize(text: str) -> list[str]:
    tokens = []
    for raw in re.findall(r"[A-Za-z0-9_]+", text):
        parts = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", raw).replace("_", " ").split()
        words = {raw.lower(), *(p.lower() for p in parts)}
        for word in words:
            if word in STOPWORDS or len(word) < 2:
                continue
            tokens.append(word[:-1] if len(word) > 3 and word.endswith("s") and not word.endswith("ss") else word)
    return tokens


def search(root: Path, wiki: Path, query: str, feature: str | None, limit: int) -> int:
    docs = []
    for page in load_pages(wiki, feature):
        meta_text = " ".join(
            page.field(k) for k in ("title", "summary", "keywords", "aliases", "questions")
        )
        meta_tokens = tokenize(meta_text)
        for chunk in page.chunks():
            terms = tokenize(chunk["text"]) + tokenize(chunk["heading"]) * 3 + meta_tokens * 2
            docs.append({"page": page, "chunk": chunk, "tf": Counter(terms), "length": len(terms)})
    if not docs:
        print("No wiki pages to search.")
        return 0
    query_terms = list(dict.fromkeys(tokenize(query)))
    average = sum(d["length"] for d in docs) / len(docs)
    k1, b = 1.4, 0.6
    frequency = {t: sum(1 for d in docs if t in d["tf"]) for t in query_terms}
    results = []
    for doc in docs:
        score = 0.0
        for term in query_terms:
            tf = doc["tf"].get(term, 0)
            if tf:
                idf = math.log(1 + (len(docs) - frequency[term] + 0.5) / (frequency[term] + 0.5))
                score += idf * tf * (k1 + 1) / (tf + k1 * (1 - b + b * doc["length"] / average))
        if score > 0:
            results.append((score, doc))
    if not results:
        print("No matches. Retry with synonyms or code identifiers, or fall back to the code itself.")
        return 0
    results.sort(key=lambda r: -r[0])
    use_git = is_git(root)
    shown: Counter = Counter()
    for score, doc in results:
        page, chunk = doc["page"], doc["chunk"]
        if shown[page.rel] >= MAX_RESULTS_PER_PAGE or sum(shown.values()) >= limit:
            continue
        shown[page.rel] += 1
        stale = stale_commits(root, page) if use_git and page.tracks_code else []
        flag = f"  [STALE: {len(stale)} code commit(s) since last update, verify against code]" if stale else ""
        tag = f"  {page.tag}" if page.tag else ""
        print(f"{WIKI}/{page.rel}:{chunk['start']}-{chunk['end']}  score={score:.2f}{tag}{flag}")
        print(f"  {page.field('title')} > {chunk['heading']}")
        best = max(
            (l.strip() for l in chunk["text"].split("\n")[1:] if l.strip()),
            key=lambda l: sum(1 for t in tokenize(l) if t in query_terms),
            default="",
        )
        if best:
            print(f"  {best[:160]}")
    return 0


