def write_page(path: Path, title: str, slug: str, kind: str, sources: list[str], status: str = "") -> None:
    source_block = "".join(f"  - {s}\n" for s in sources) if kind not in SOURCELESS_TYPES else ""
    sources_line = f"sources:\n{source_block}" if source_block else ""
    today = dt.date.today().isoformat()
    prefilled = {"Open questions": "None.", "History": f"- {today}: Created as {status}."}
    headings = "".join(
        f"## {h}\n\n{prefilled.get(h, '<!-- fill -->') if kind == 'design' else '<!-- fill -->'}\n\n"
        for h in PAGE_TYPES[kind]
    )
    if kind == "changelog":
        headings = f"## {today}: Wiki page created\n\n<!-- fill: what changed and why -->\n"
    summary = "<!-- fill: one sentence naming the concrete choices -->"
    status_line = f"status: {status}\n" if kind in STATUS_TYPES else ""
    extra = "" if kind in SOURCELESS_TYPES else (
        "keywords: []\naliases: []\nquestions:\n  - <!-- fill: a question this page answers -->\n"
    )
    path.write_text(
        f"---\ntitle: {title}\nfeature: {slug}\ntype: {kind}\n{status_line}summary: {summary}\n"
        f"{extra}{sources_line}---\n\n# {title}\n\n{headings.rstrip()}\n",
        encoding="utf-8", newline="\n",
    )


def init(root: Path) -> Path:
    wiki = root / WIKI
    if (wiki / MARKER).exists():
        return wiki
    if wiki.exists() and any(wiki.iterdir()):
        fail(f"{wiki} already exists and is not a feature wiki; nothing was changed. Ask the user how to proceed.")
    (wiki / "features").mkdir(parents=True, exist_ok=True)
    (wiki / MARKER).write_text("1\n", encoding="utf-8")
    (wiki / "README.md").write_text(README, encoding="utf-8", newline="\n")
    build(wiki)
    return wiki


