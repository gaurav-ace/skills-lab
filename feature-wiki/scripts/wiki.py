EDIT_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}
NOISE_TAGS = re.compile(
    r"<(system-reminder|local-command-stdout|local-command-stderr|local-command-caveat|command-name|"
    r"command-message|command-args|task-notification)>.*?</\1>",
    re.DOTALL,
)
MAX_USER_CHARS = 3000
MAX_CLAUDE_CHARS = 2000
MAX_SUMMARY_DIGEST_CHARS = 8000
MAX_ERROR_CHARS = 300


def transcript_files() -> list[Path]:
    config = Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude")
    return list((config / "projects").glob("*/*.jsonl"))


def read_events(path: Path):
    """Conversation events on the main thread, without subagent or harness records."""
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if '"user"' not in line and '"assistant"' not in line:
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            if event.get("type") in ("user", "assistant") and not event.get("isSidechain"):
                yield event


def content_blocks(event: dict) -> list[dict]:
    content = (event.get("message") or {}).get("content")
    if isinstance(content, str):
        return [{"type": "text", "text": content}]
    return [b for b in content if isinstance(b, dict)] if isinstance(content, list) else []


def clean_text(text: str) -> str:
    return NOISE_TAGS.sub("", text).strip()


def clip(text: str, limit: int) -> str:
    return text if len(text) <= limit else f"{text[:limit]}\n[...cut {len(text) - limit} chars]"


def redact(text: str) -> str:
    for pattern in SECRET_PATTERNS:
        text = pattern.sub("[REDACTED]", text)
    return text


def is_within(path: str, root: str) -> bool:
    return path == root or path.startswith(root.rstrip("/") + "/")


def session_title(path: Path) -> str:
    title = ""
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if '"ai-title"' in line:
                try:
                    title = json.loads(line).get("aiTitle", title)
                except json.JSONDecodeError:
                    pass
    return title


def summarize_session(path: Path, root: str) -> dict | None:
    """Stats for a transcript, or None if it never worked in this repo.

    Sessions are matched on working directory and edited paths, not on the folder the
    transcript is stored under, because a session started in a parent folder still counts.
    """
    with open(path, encoding="utf-8", errors="replace") as handle:
        if not any(root in line for line in handle):
            return None
    touched, edits, prompts, first, last = False, set(), 0, "", ""
    for event in read_events(path):
        touched = touched or is_within(event.get("cwd") or "", root)
        last = event.get("timestamp") or last
        for block in content_blocks(event):
            if block.get("type") == "tool_use" and block.get("name") in EDIT_TOOLS:
                target = (block.get("input") or {}).get("file_path") or ""
                if is_within(target, root):
                    edits.add(target)
                    touched = True
            elif block.get("type") == "text" and event["type"] == "user" and not event.get("isMeta"):
                text = clean_text(block.get("text") or "")
                if text:
                    prompts += 1
                    first = first or text
    if not touched:
        return None
    return {"path": path, "id": path.stem, "last": last, "edits": len(edits), "prompts": prompts,
            "first": first, "title": session_title(path)}


def repo_sessions(root: Path) -> list[dict]:
    found = (summarize_session(p, str(root)) for p in transcript_files())
    return sorted((s for s in found if s), key=lambda s: s["last"], reverse=True)


def resolve_session(ref: str, root: Path) -> Path:
    if ref == "current":
        ref = os.environ.get("CLAUDE_CODE_SESSION_ID") or "latest"
    if ref == "latest":
        sessions = repo_sessions(root)
        if not sessions:
            fail(f"no Claude Code session found for {root}", 3)
        return sessions[0]["path"]
    direct = Path(ref).expanduser()
    if direct.suffix == ".jsonl" and direct.is_file():
        return direct
    hits = [p for p in transcript_files() if p.stem.startswith(ref)]
    if len(hits) != 1:
        fail(f"{len(hits)} transcripts match '{ref}'. Run: wiki.py sessions", 3)
    return hits[0]


def render_digest(path: Path, root: str) -> str:
    """Keep what explains intent: prompts, replies, answers, edited files, commits, failures.

    Drops thinking and successful tool output, which make up most of a transcript.
    """
    out = [f"# Session digest: {session_title(path) or path.stem}", "",
           f"Session {path.stem}. Secret-like strings redacted, so read the rest as private.", ""]
    pending: dict[str, dict] = {}
    edited: list[str] = []
    day = ""

    def flush() -> None:
        if edited:
            out.append("EDITED: " + ", ".join(dict.fromkeys(edited)))
            out.append("")
            edited.clear()

    for event in read_events(path):
        stamp = (event.get("timestamp") or "")[:10]
        if stamp and stamp != day:
            day = stamp
            flush()
            out += [f"## {day}", ""]
        for block in content_blocks(event):
            kind = block.get("type")
            if kind == "text" and not event.get("isMeta"):
                text = clean_text(block.get("text") or "")
                if not text:
                    continue
                flush()
                if event.get("isCompactSummary"):
                    out += [f"CONTEXT SUMMARY: {clip(text, MAX_SUMMARY_DIGEST_CHARS)}", ""]
                elif event["type"] == "user":
                    out += [f"USER: {clip(text, MAX_USER_CHARS)}", ""]
                else:
                    out += [f"CLAUDE: {clip(text, MAX_CLAUDE_CHARS)}", ""]
            elif kind == "tool_use":
                name, given = block.get("name"), block.get("input") or {}
                pending[block.get("id")] = {"name": name, "input": given}
                if name in EDIT_TOOLS and given.get("file_path"):
                    target = given["file_path"]
                    edited.append(os.path.relpath(target, root) if is_within(target, root) else target)
                elif name == "Bash" and re.search(r"\bgit\s+(commit|revert|reset)\b", given.get("command") or ""):
                    flush()
                    out += [f"GIT: {clip(given['command'], 400)}", ""]
                elif name == "AskUserQuestion":
                    flush()
                    asked = [q.get("question", "") for q in given.get("questions") or []]
                    out += [f"ASKED: {' / '.join(asked)}", ""]
            elif kind == "tool_result":
                call = pending.pop(block.get("tool_use_id"), None)
                if not call:
                    continue
                body = block.get("content")
                if isinstance(body, list):
                    body = " ".join(b.get("text", "") for b in body if isinstance(b, dict))
                body = clean_text(body or "")
                if call["name"] == "AskUserQuestion":
                    out += [f"ANSWER: {clip(body, MAX_USER_CHARS)}", ""]
                elif block.get("is_error"):
                    flush()
                    what = call["input"].get("command") or call["input"].get("file_path") or ""
                    out += [f"FAILED {call['name']}: {clip(str(what), 200)}\n  {clip(body, MAX_ERROR_CHARS)}", ""]
    flush()
    return redact("\n".join(out)).rstrip() + "\n"


