def validate(root: Path, wiki: Path, feature: str | None) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    pages = load_pages(wiki, feature)
    all_pages = load_pages(wiki)
    known = {p.id for p in all_pages}
    files = all_files(root)
    use_git = is_git(root)

    for slug in sorted({p.slug for p in pages} - {ROOT_SLUG}):
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
            errors.append(f"features/{slug}: folder name must be kebab-case")
        if f"{slug}/overview" not in known:
            errors.append(f"features/{slug}: missing overview.md")
        if f"{slug}/learning" not in known:
            errors.append(f"features/{slug}: missing {LEARNING_FILE}, run build")

    for page in pages:
        where = page.rel
        if not page.meta:
            errors.append(f"{where}: missing or unterminated frontmatter")
            continue
        for name in REQUIRED_FIELDS:
            if not page.field(name):
                errors.append(f"{where}: missing '{name}'")
        if page.field("feature") and page.field("feature") != page.slug:
            errors.append(f"{where}: feature '{page.field('feature')}' does not match folder '{page.slug}'")
        kind = page.field("type")
        if kind and kind not in PAGE_TYPES:
            errors.append(f"{where}: unknown type '{kind}' (use: {', '.join(PAGE_TYPES)})")
        if "<!-- fill" in page.text:
            errors.append(f"{where}: unfilled template placeholder")
        for related in as_list(page.meta.get("related")):
            if related not in known:
                errors.append(f"{where}: related page '{related}' does not exist")
        for target in re.findall(r"\]\(([^)#\s]+\.md)(?:#[^)]*)?\)", page.text):
            if not re.match(r"[a-z]+://", target) and not (page.path.parent / target).resolve().exists():
                errors.append(f"{where}: broken link {target}")
        status = page.status
        if status and status not in STATUSES:
            errors.append(f"{where}: unknown status '{status}' (use: {', '.join(STATUSES)})")
        if kind in STATUS_TYPES and not status:
            errors.append(f"{where}: missing 'status' (use: {', '.join(STATUSES)})")
        if status == "implemented" and not page.sources:
            errors.append(f"{where}: implemented but has no 'sources'; list the code that implements it")
        if status == "superseded" and page.field("superseded_by") not in known:
            errors.append(f"{where}: superseded, so 'superseded_by' must name an existing page id")
        if kind == "design" and status != "proposed":
            headings = {s["heading"] for s in page.sections}
            for section in DESIGN_SECTIONS:
                if section not in headings:
                    warnings.append(f"{where}: design page has no '## {section}' section")
        if kind not in SOURCELESS_TYPES:
            if not page.sources and page.tracks_code:
                warnings.append(f"{where}: no 'sources', so staleness cannot be detected")
            if not as_list(page.meta.get("keywords")):
                warnings.append(f"{where}: no 'keywords', so search recall will suffer")
        if FILLER_SUMMARY.search(page.field("summary")):
            warnings.append(f"{where}: summary is generic; name the concrete choices, it is the retrieval key")
        if page.tracks_code:
            for source in page.sources:
                if not any(glob_regex(source).match(f) for f in files):
                    warnings.append(f"{where}: source '{source}' matches no files (moved or deleted?)")
        if len(page.field("summary")) > MAX_SUMMARY_CHARS:
            warnings.append(f"{where}: summary over {MAX_SUMMARY_CHARS} chars; it is loaded on every lookup")
        if page.line_count > MAX_PAGE_LINES:
            warnings.append(f"{where}: {page.line_count} lines; split it (limit {MAX_PAGE_LINES})")
        if use_git and status != "superseded":
            stale = stale_commits(root, page)
            if stale and status in PLANNED_STATUSES:
                warnings.append(f"{where}: still '{status}' but its code has changed since. "
                                "If this design is built, set status: implemented")
            elif stale:
                warnings.append(f"{where}: STALE, {len(stale)} code commit(s) since last update, latest: {stale[0]}")

    for path in sorted(wiki.rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for pattern in SECRET_PATTERNS:
            if pattern.search(text):
                errors.append(f"{path.relative_to(wiki).as_posix()}: looks like a secret ({pattern.pattern[:24]}...)")
                break

    for path, content in expected_indexes(wiki).items():
        if not path.exists() or path.read_text(encoding="utf-8", errors="replace") != content:
            errors.append(f"{path.relative_to(wiki).as_posix()}: out of date, run build")
    return errors, warnings


