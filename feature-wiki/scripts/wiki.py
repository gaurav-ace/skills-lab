def cmd_publish(args) -> int:
    root = find_root(args.root)
    wiki = require_wiki(root)
    build(wiki)
    errors, warnings = validate(root, wiki, None)
    for line in warnings:
        print(f"WARN    {line}")
    if errors:
        for line in errors:
            print(f"ERROR   {line}")
        return result("blocked", "Fix the errors above. Nothing was committed.", 1)
    if not is_git(root):
        return result("local-only", "Not a git repository, so the wiki was saved locally and not pushed.")

    changed_docs = status_entries(root, WIKI)
    if changed_docs and not args.allow_dirty_sources:
        changed_pages = [p for p in load_pages(wiki) if f"{WIKI}/{p.rel}" in changed_docs and p.tracks_code]
        dirty = [f for f in status_entries(root) if not f.startswith(f"{WIKI}/")]
        held = sorted(f for f in dirty if any(matches(f, p.sources) for p in changed_pages))
        if held:
            sample = ", ".join(held[:5])
            return result(
                "held-uncommitted-code",
                f"The wiki changes describe code that is not committed yet: {sample}\n"
                "wiki/ is left uncommitted. Commit it together with that code. If that code is "
                "unrelated work, rerun with --allow-dirty-sources.",
            )

    if changed_docs:
        added = git(root, "add", "--", WIKI)
        if added.returncode:
            return result("commit-failed", added.stderr.strip(), 1)
        committed = git(root, "commit", "-m", args.message, "--", WIKI)
        if committed.returncode:
            return result("commit-failed", (committed.stdout + committed.stderr).strip(), 1)
        print(f"committed wiki changes: {git_out(root, 'rev-parse', '--short', 'HEAD')}")

    if args.no_push:
        return result("committed-not-pushed", "--no-push was given.")
    branch = git_out(root, "symbolic-ref", "--short", "-q", "HEAD")
    if not branch:
        return result("held-push", "Detached HEAD, so there is no branch to push.")
    remote = git_out(root, "config", f"branch.{branch}.remote")
    has_upstream = bool(remote and git_out(root, "rev-parse", "--abbrev-ref", "@{u}"))
    if not remote:
        remotes = (git_out(root, "remote") or "").split()
        if not remotes:
            return result("local-only", "No git remote is configured, so the wiki is committed locally.")
        remote = "origin" if "origin" in remotes else remotes[0]

    git(root, "fetch", remote, branch)
    scope = ["@{u}..HEAD"] if has_upstream else ["HEAD", "--not", f"--remotes={remote}"]
    if has_upstream and (git_out(root, "rev-list", "--count", "HEAD..@{u}") or "0") != "0":
        return result(
            "held-push",
            f"{branch} is behind {remote}, and force-pushing is never an option. Run `git pull --rebase`, "
            "resolve any INDEX.md conflict by running build, then publish again.",
        )
    unpushed = git_out(root, "log", "--format=%h", *scope) or ""
    if not unpushed:
        return result("up-to-date", "Nothing to push.")
    touched = git_out(root, "log", "--format=", "--name-only", *scope) or ""
    code_files = sorted({f for f in touched.split("\n") if f and not f.startswith(f"{WIKI}/")})
    if code_files:
        return result(
            "held-push",
            f"{branch} has unpushed commits touching {len(code_files)} code file(s), e.g. {code_files[0]}. "
            "Pushing would ship that code too, so the wiki stays local until the user pushes the branch.",
        )
    command = ["push", "-u", remote, branch] if not has_upstream else ["push", remote, branch]
    pushed = git(root, *command)
    if pushed.returncode:
        return result("push-failed", f"Committed locally, push failed:\n{pushed.stderr.strip()}", 2)
    return result("pushed", f"Wiki pushed to {remote}/{branch}.")


