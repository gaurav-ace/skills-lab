def cmd_mark_reviewed(args) -> int:
    root = find_root(args.root)
    require_wiki(root)
    stamp = dt.date.today().isoformat()
    head = git_out(root, "rev-parse", "--short", "HEAD") if is_git(root) else None
    value = f"reviewed: {stamp}" + (f" {head}" if head else "")
    for name in args.pages:
        path = Path(name)
        path = path if path.is_absolute() else Path.cwd() / path
        if not path.is_file():
            fail(f"no such page: {name}")
        with open(path, encoding="utf-8", newline="") as handle:
            lines = handle.read().split("\n")
        if lines[0].strip() != "---":
            fail(f"{name} has no frontmatter")
        closing = next((i for i, l in enumerate(lines[1:], 1) if l.strip() == "---"), None)
        if closing is None:
            fail(f"{name} has unterminated frontmatter")
        ending = "\r" if lines[0].endswith("\r") else ""
        existing = next((i for i in range(1, closing) if lines[i].startswith("reviewed:")), None)
        if existing is None:
            lines.insert(closing, value + ending)
        else:
            lines[existing] = value + ending
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write("\n".join(lines))
        print(f"{name}: {value}")
    return 0


