        path = folder / f"{kind}.md"
        if path.exists():
            print(f"exists, kept: {path.relative_to(root).as_posix()}")
            continue
        label = args.title if kind == "overview" else f"{args.title}: {kind}"
        write_page(path, label, args.slug, kind, sources, args.status)
        print(f"created: {path.relative_to(root).as_posix()}")
